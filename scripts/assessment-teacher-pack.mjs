#!/usr/bin/env node
// Generates the compact teacher-review pack from the blueprints themselves.
// It is not an approval record. Every status printed here is read from the
// authored blueprint, and a reviewer's signature is a separate, human act.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { compileEngines } from "./compile-engines.mjs";

compileEngines();
const require = createRequire(import.meta.url);
const { DIET_DIGESTION_BLUEPRINT } = require("../.verify/assessment-blueprints/diet-digestion.js");
const { PHYSICS_ENERGY_BLUEPRINT } = require("../.verify/assessment-blueprints/physics-energy.js");
const { MATHS_TABLES_BLUEPRINT } = require("../.verify/assessment-blueprints/maths-tables.js");
const { assessmentServingDecision } = require("../.verify/assessment-intelligence.js");

const blueprints = [DIET_DIGESTION_BLUEPRINT, PHYSICS_ENERGY_BLUEPRINT, MATHS_TABLES_BLUEPRINT];
const generatedAt = new Date().toISOString();
const dir = path.join(process.cwd(), "reports", "assessment-teacher-review");
fs.mkdirSync(dir, { recursive: true });

const pack = {
  generatedBy: "scripts/assessment-teacher-pack.mjs",
  generatedAt,
  status: "UNREVIEWED — NOT AN APPROVAL",
  instruction:
    "A subject teacher reviews each item, its model answer, criteria and alternatives. Return a dated review record naming this blueprint version and the reviewer's role. Until that record exists, the item is not servable.",
  blueprints: blueprints.map((bp) => ({
    id: bp.id,
    version: bp.version,
    title: bp.title,
    subject: bp.subject,
    level: bp.level,
    reviewStatus: bp.reviewStatus,
    serving: assessmentServingDecision(bp),
    sources: bp.sources.map((source) => ({
      id: source.id,
      label: source.label,
      availability: source.availability,
      rights: source.rights,
      licensing: source.licensing,
      allowedUse: source.allowedUse,
      reproduction: source.reproduction,
      sourceTextStored: source.containsSourceText,
      studentDataObserved: source.studentDataObserved,
      note: source.note,
    })),
    items: bp.items.map((item) => ({
      id: item.id,
      conceptId: item.conceptId,
      archetypeId: item.archetypeId,
      responseKind: item.responseKind,
      marks: item.marks,
      prompt: item.prompt,
      modelAnswer: item.modelAnswer,
      numeric: item.numeric ?? null,
      table: item.table ?? null,
      criteria: item.criteria,
      partialCreditRule: item.partialCreditRule,
      reviewStatus: item.reviewStatus,
      originality: item.originality,
      sourceTextReproduced: item.sourceTextReproduced,
    })),
    misconceptions: bp.misconceptions,
    limitations: bp.limitations,
  })),
};

fs.writeFileSync(path.join(dir, "pack.json"), `${JSON.stringify(pack, null, 2)}\n`);

const lines = [
  "# Assessment teacher-review pack",
  "",
  `Generated by \`scripts/assessment-teacher-pack.mjs\` on ${generatedAt}.`,
  "",
  "> **Status: UNREVIEWED — NOT AN APPROVAL.** No teacher has reviewed these items.",
  "> This pack is the material a reviewer reads, not a record that one did.",
  "",
  "## How to review",
  "",
  "1. Read the item and answer it yourself before reading the model answer.",
  "2. Check the mathematics or science, the mark allocation and every accepted alternative.",
  "3. Check that no distractor is unfair, ambiguous or accidentally correct.",
  "4. Check that the named misconception is the one the item can actually reveal.",
  "5. Write a dated record for THE VERSION below, with your name and role, and a verdict. Do not edit this file as if it were that record.",
  "6. If rights or licensing are unknown, do not approve reproduction. Review and clearance are separate.",
  "",
  "## Blueprints",
  "",
];

for (const bp of blueprints) {
  const decision = assessmentServingDecision(bp);
  lines.push(`### ${bp.title}`, "");
  lines.push(`- Id: \`${bp.id}\` (version \`${bp.version}\`)`);
  lines.push(`- Subject / level: ${bp.subject} / ${bp.level}`);
  lines.push(`- Review status: **${bp.reviewStatus}**; servable: **${decision.ok ? "yes" : "no"}**`);
  lines.push(`- Items: ${bp.items.length}; marks: ${bp.items.reduce((n, item) => n + item.marks, 0)}`);
  if (!decision.ok) lines.push(`- Refusal: ${decision.reasons.join("; ")}`);
  lines.push("", "**Sources and statuses**", "", "| Source | Availability | Rights | Licensing | Use | Text stored |", "| --- | --- | --- | --- | --- | --- |");
  for (const s of bp.sources) {
    lines.push(`| ${s.label} | ${s.availability} | ${s.rights} | ${s.licensing} | ${s.allowedUse} / ${s.reproduction} | ${s.containsSourceText} |`);
  }
  lines.push("", "**Items**", "");
  for (const item of bp.items) {
    lines.push(`#### \`${item.id}\` — ${item.marks} mark${item.marks === 1 ? "" : "s"} — ${item.responseKind}`, "");
    lines.push(`Concept: \`${item.conceptId}\` · archetype: \`${item.archetypeId}\` · item review: **${item.reviewStatus}**`, "");
    lines.push(`**Prompt**: ${item.prompt}`, "");
    lines.push(`**Model answer**: ${item.modelAnswer}`, "");
    lines.push("**Marking criteria**:", "");
    for (const c of item.criteria) {
      lines.push(`- \`${c.id}\` (${c.kind}, ${c.marks} mark${c.marks === 1 ? "" : "s"}): ${c.credit}`);
      if (c.acceptable?.length) lines.push(`  - Accept: ${c.acceptable.join("; ")}`);
      if (c.nonCredit) lines.push(`  - Does not earn: ${c.nonCredit}`);
      if (c.misconceptionId) lines.push(`  - Diagnostic belief: \`${c.misconceptionId}\``);
    }
    lines.push(`- Partial credit: ${item.partialCreditRule}`);
    if (item.table) {
      lines.push("", "**Table key** (shown here because a reviewer must see it; the learner page does not):", "");
      lines.push(`| Row | ${item.table.columns.join(" | ")} |`);
      lines.push(`| --- | ${item.table.columns.map(() => "---").join(" | ")} |`);
      for (const row of item.table.rows) {
        lines.push(`| ${row.label ?? ""} | ${row.cells.map((c) => c.given ?? String(c.answer ?? "")).join(" | ")} |`);
      }
    }
    lines.push("", "**Reviewer decision**: ☐ accurate  ☐ changes needed  ☐ reject", "", "**Reviewer notes**:", "", "---", "");
  }
  lines.push("**Named misconceptions**", "");
  for (const m of bp.misconceptions) {
    lines.push(`- \`${m.id}\` — ${m.label}. Why wrong: ${m.whyWrong}`);
  }
  lines.push("", "**Stated limitations**", "", ...bp.limitations.map((l) => `- ${l}`), "");
}

fs.writeFileSync(path.join(dir, "PACK.md"), `${lines.join("\n")}\n`);
console.log(`wrote ${path.relative(process.cwd(), path.join(dir, "PACK.md"))} and pack.json`);
console.log("status: UNREVIEWED — NOT AN APPROVAL; 0 teacher reviews, 0 servable blueprints");
