// ─────────────────────────────────────────────────────────────────────────────
// ONE FILE THAT SAYS WHAT THIS REPOSITORY MEASURES — and one README table
// rendered from it (§30).
//
// WHY THIS EXISTS. The project publishes a lot of numbers about itself: 135
// concepts, 53 misconceptions, 5 verified concepts, 19 national routes, 72
// gate-passed checks, 84 concepts with an option-length tell. They were spread
// across a genome, several audit artefacts, a handful of gates and — worst —
// prose written by hand in summaries and READMEs, where each was correct on the
// day it was typed. Two of them had already drifted: the README said "25
// specifications across 20 countries" while the registry held 30 over 19, and the
// engine suite's own count (1075 → 2933) has moved twice with no code change,
// because per-concept loops iterate over real content.
//
// THE RULE HERE, and the reason it is a script rather than a document:
//
//     A published number is DERIVED from the artifact that makes it true, and
//     it lives in exactly one file. If it moves, `npm run status:check` fails the
//     build until the file is regenerated — so the diff is the review, and a
//     summary cannot quietly disagree with the repository.
//
// WHAT IT DELIBERATELY DOES NOT DO: restate the result of a RUN. "72 passed" is
// true of the last `content-gate` on this machine and false of the repository,
// so runtime results stay in CI's output and are not frozen here as facts. Every
// row below is a property of the committed content.
//
// Run:  npm run status          (writes audit/status.json and the README table)
//       npm run status:check    (fails if either is stale; writes nothing)
// ─────────────────────────────────────────────────────────────────────────────
import { compileEngines } from "./compile-engines.mjs";
import { createRequire } from "node:module";
import fs from "node:fs";

compileEngines();
const require = createRequire(import.meta.url);
const G = require("../.verify/genome.js");
const M = require("../.verify/misconceptions.js");
const S = require("../.verify/specifications.js");
const R = require("../.verify/curricula/registry.js");
const I = require("../.verify/i18n.js");

const CHECK = process.argv.includes("--check");
const STATUS_PATH = "audit/status.json";
const README_PATH = "README.md";
const BEGIN = "<!-- status:begin — generated by `npm run status`; edits are overwritten -->";
const END = "<!-- status:end -->";

const readJson = (p) => {
  try { return JSON.parse(fs.readFileSync(p, "utf8")); } catch { return null; }
};

// ── The numbers ─────────────────────────────────────────────────────────────
// Every row names its own source, so a reader can go and check it. A section
// whose artefact is missing is reported as MISSING rather than as zero: "we did
// not measure" and "we measured none" are different claims, which is the same
// rule the learner-facing surfaces follow.
// ── Storage, derived from the source that implements it ─────────────────────
// These are the inventory numbers docs/STORAGE_SPEC.md reasons from, and they
// are exactly the kind that drift: the count of route files importing the store
// changed the same day slice 0 gave app/api/hub-status an import (19 → 20), and
// a spec that had typed "19" would have been wrong within the hour. So they are
// measured here, the spec cites them rather than owning them, and `status:check`
// fails if the two ever disagree.
const stripComments = (src) =>
  src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/[^\n]*/g, "$1");
const sourceFilesUnder = (dir, out = []) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = `${dir}/${entry.name}`;
    if (entry.isDirectory()) sourceFilesUnder(full, out);
    else if (/\.(ts|tsx)$/.test(entry.name)) out.push(full);
  }
  return out;
};
const STORE_FILE = "lib/server/store.ts";
const storeSource = fs.readFileSync(STORE_FILE, "utf8");
const storeExports = (storeSource.match(/^export /gm) ?? []).length;
const storeLines = storeSource.split("\n").length;
const appAndLib = [...sourceFilesUnder("lib"), ...sourceFilesUnder("app")];
const routeImporters = sourceFilesUnder("app/api")
  .filter((f) => /from "@\/lib\/server\/store"/.test(fs.readFileSync(f, "utf8"))).length;
const lockTables = appAndLib.filter((f) =>
  /new Map<string, Promise<unknown>>\s*\(\s*\)/.test(stripComments(fs.readFileSync(f, "utf8")))).length;
// Counts OWNERS for both rows, so anything other than 1 is the regression — the
// first cut of this counted only offenders and reported 0 for the data directory
// beside a 1 for the lock table, which read as two different questions. `lib/env.ts`
// is exempt: it REPORTS the variable's state to an operator and resolves nothing.
const dataDirResolvers = appAndLib.filter((f) =>
  f !== "lib/env.ts" && /OPENMIND_DATA_DIR/.test(stripComments(fs.readFileSync(f, "utf8")))).length;
// The named files the server modules read and write. `evidence/` is a directory
// of per-learner ledgers and `session-secret` is not JSON, so neither is here —
// the note on the row says so rather than letting the count imply completeness.
const storeDataFiles = new Set(
  fs.readdirSync("lib/server")
    .filter((f) => f.endsWith(".ts"))
    .flatMap((f) => fs.readFileSync(`lib/server/${f}`, "utf8").match(/"[a-z-]+\.json"/g) ?? []),
);

const vcov = readJson("audit/verification-coverage.json");
const reviews = readJson("audit/item-reviews.json")?.reviews ?? [];
const optionsGate = readJson("audit/options-gate.json");
const contentCoverage = readJson("audit/content-coverage.json");
const pilotPack = readJson("audit/pilot-pack.json");

const bySubject = {};
for (const c of G.CONCEPTS) bySubject[c.subject] = (bySubject[c.subject] ?? 0) + 1;
const byStage = {};
for (const c of G.CONCEPTS) byStage[c.stage] = (byStage[c.stage] ?? 0) + 1;

const rows = [
  { section: "Content", label: "Teachable concepts", value: G.CONCEPTS.length, source: "lib/genome.ts", note: Object.entries(bySubject).map(([k, v]) => `${k} ${v}`).join(" · ") },
  { section: "Content", label: "Concepts by stage", value: Object.entries(byStage).map(([k, v]) => `${k}:${v}`).join(" "), source: "lib/genome.ts", note: "stage 0 (primary) → 5" },
  { section: "Content", label: "Concepts with a named misconception", value: G.CONCEPTS.filter((c) => (c.misconceptions ?? []).length > 0).length, source: "lib/genome.ts", note: `catalogue of ${M.MISCONCEPTIONS.length} patterns` },
  { section: "Content", label: "Languages", value: I.LANGS.length, source: "lib/i18n.ts" },

  { section: "Content verification", label: "Concepts with a structural check", value: vcov?.layers?.structure ?? "MISSING", source: "audit/verification-coverage.json", note: "four distinct options, no float noise, a non-empty explanation" },
  { section: "Content verification", label: "Concepts whose explanation states its key", value: vcov?.layers?.explanationKey ?? "MISSING", source: "audit/verification-coverage.json" },
  { section: "Content verification", label: "Concepts independently re-derived from the prompt", value: vcov?.layers?.promptDerived?.length ?? "MISSING", source: "audit/verification-coverage.json", note: (vcov?.layers?.promptDerived ?? []).join(", ") },
  { section: "Content verification", label: "Concepts checked for structure only", value: vcov?.layers?.structuralOnly?.length ?? "MISSING", source: "audit/verification-coverage.json", note: "an item no matcher recognises is an item nobody has verified" },
  { section: "Content verification", label: "Concepts reviewed by a qualified person", value: reviews.length, source: "audit/item-reviews.json", note: reviews.length === 0 ? "nobody has reviewed any item yet — the honest figure, and the one this project would most like to change" : "" },

  { section: "Assessment validity", label: "Concepts with an option-length tell above the line", value: optionsGate ? `${optionsGate.offenders} of ${optionsGate.concepts}` : "MISSING", source: "audit/options-gate.json", note: "a learner who never reads the question should not beat chance" },
  { section: "Assessment validity", label: "Best bank-wide length strategy", value: optionsGate ? `${(optionsGate.bank.best * 100).toFixed(1)}%` : "MISSING", source: "audit/options-gate.json", note: "chance is 25%" },
  { section: "Assessment validity", label: "Course × subject rows audited for depth", value: contentCoverage?.totals?.courses ?? "MISSING", source: "audit/content-coverage.json", note: !contentCoverage?.totals ? "" : contentCoverage.totals.short === 0 ? "every subject's target depth is reachable, by some generator in its course" : `${contentCoverage.totals.short} fall short of their course's target` },

  { section: "Storage", label: "Lock tables in lib/ and app/", value: lockTables, source: "source scan", note: "one, in lib/server/store.ts — two tables means two writers with no common serialisation point" },
  { section: "Storage", label: "Owners of where learning data lives", value: dataDirResolvers, source: "source scan", note: "one, in lib/server/store.ts; lib/env.ts reports the variable and resolves nothing, so it is exempt" },
  { section: "Storage", label: "Route files importing the store", value: routeImporters, source: "app/api", note: `${storeExports} export statements in a ${storeLines}-line store; this is the surface docs/STORAGE_SPEC.md has to port` },
  { section: "Storage", label: "JSON files the server modules own", value: storeDataFiles.size, source: "lib/server/*.ts", note: `plus the per-learner evidence/*.jsonl ledgers and session-secret: ${[...storeDataFiles].sort().join(", ")}` },

  // The pilot's own burden, on the front page: how much content a teacher is
  // being asked to read. It is generated with the pack (scripts/pilot-pack.mjs),
  // so it moves when the bank moves rather than when somebody remembers to edit
  // a document.
  { section: "Pilot (UK GCSE maths)", label: "Concepts in the review cluster", value: pilotPack?.totals?.concepts ?? "MISSING", source: "audit/pilot-pack.json", note: "computed from the genome's prerequisite graph, not hand-picked" },
  { section: "Pilot (UK GCSE maths)", label: "Items awaiting human review", value: pilotPack?.totals?.items ?? "MISSING", source: "audit/pilot-pack.json", note: "every item a learner in the cluster meets, at a seed the reviewer can reproduce" },
  { section: "Pilot (UK GCSE maths)", label: "Cluster concepts with no named misconception to probe", value: pilotPack ? pilotPack.totals.concepts - pilotPack.totals.withMisconceptions : "MISSING", source: "audit/pilot-pack.json", note: "a distractor here is not yet tied to a pattern anyone has written down" },

  { section: "Curriculum", label: "Country codes offered in enrolment", value: I.COUNTRIES.length, source: "lib/i18n.ts" },
  { section: "Curriculum", label: "Countries with a recorded national route", value: R.nationalRouteCodes().length, source: "lib/curricula/registry.ts", note: "asserted equal to the published count by `npm run curriculum-gate`" },
  { section: "Curriculum", label: "National pathways", value: R.allPathways().filter((p) => p.pathwayType === "national").length, source: "lib/curricula/registry.ts", note: "Cameroon runs two systems, so this exceeds the country count" },
  { section: "Curriculum", label: "Offerings without a national route", value: I.COUNTRIES.filter((c) => (R.countryRecord(c.code)?.nationalPathways ?? []).length === 0).length, source: "lib/curricula/registry.ts", note: "offered the international programmes and the skills pathway, explicitly" },
  { section: "Curriculum", label: "Specifications", value: S.SPECIFICATIONS.length, source: "lib/specifications.ts", note: `${S.SPECIFICATIONS.filter((s) => s.country !== "INT" && s.country !== "XX").length} national · 2 international · 1 independent` },
  { section: "Curriculum", label: "Pathways with no structural source on file", value: R.allPathways().filter((p) => p.sourceUrls.length === 0).length, source: "lib/curricula/registry.ts", note: "named on every `curriculum-gate` run rather than hidden" },
  { section: "Curriculum", label: "Pathways whose syllabus mapping has been reviewed", value: R.allPathways().filter((p) => R.reviewAtLeast(p.mappingReview, "reviewed")).length, source: "lib/curricula/registry.ts", note: "every mapping is currently OpenMind's own" },
];

const bySection = {};
for (const row of rows) (bySection[row.section] ??= []).push(row);

const status = {
  generatedBy: "scripts/status-report.mjs",
  note:
    "Properties of the COMMITTED content, each derived from the artifact that makes it true. " +
    "Runtime results (how many assertions a gate passed on the last run) are deliberately absent: " +
    "they are true of a run and false of the repository. Regenerate with `npm run status`; " +
    "`npm run status -- --check` fails when this file or the README table is stale.",
  counts: Object.fromEntries(rows.map((r) => [`${r.section} · ${r.label}`, r.value])),
  rows,
};

// ── The README table ────────────────────────────────────────────────────────
const table = [
  BEGIN,
  "",
  "**What this repository measures.** Generated from the artifacts that make each number true;",
  "`npm run status:check` fails the build when this table or `audit/status.json` is stale.",
  "Runtime results are not listed here on purpose — a gate's last pass count is true of a run, not of the repository.",
  "",
  "| | Measured | Value | Note | Where it comes from |",
  "|---|---|---|---|---|",
];
let lastSection = "";
for (const row of rows) {
  const section = row.section === lastSection ? "" : `**${row.section}**`;
  lastSection = row.section;
  table.push(`| ${section} | ${row.label} | ${row.value} | ${row.note || ""} | \`${row.source}\` |`);
}
table.push("", END);

const readme = fs.readFileSync(README_PATH, "utf8");
const start = readme.indexOf(BEGIN);
const endAt = readme.indexOf(END);
let nextReadme;
if (start !== -1 && endAt !== -1 && endAt > start) {
  nextReadme = readme.slice(0, start) + table.join("\n") + readme.slice(endAt + END.length);
} else {
  // First run: install it directly under the Verification heading.
  const heading = "## Verification\n";
  const at = readme.indexOf(heading);
  if (at === -1) {
    console.error("README has no `## Verification` heading to install the table under");
    process.exit(2);
  }
  const insertAt = at + heading.length;
  nextReadme = `${readme.slice(0, insertAt)}\n${table.join("\n")}\n${readme.slice(insertAt)}`;
}

const nextStatus = JSON.stringify(status, null, 2) + "\n";
const currentStatus = fs.existsSync(STATUS_PATH) ? fs.readFileSync(STATUS_PATH, "utf8") : null;

if (CHECK) {
  const problems = [];
  if (currentStatus !== nextStatus) problems.push(`${STATUS_PATH} is stale (run \`npm run status\`)`);
  if (nextReadme !== readme) problems.push(`${README_PATH}'s status table is stale (run \`npm run status\`)`);
  if (problems.length > 0) {
    console.error("✗ status report:");
    for (const p of problems) console.error(`  · ${p}`);
    process.exit(1);
  }
  console.log(`✓ status report is current (${rows.length} measured numbers)`);
  process.exit(0);
}

fs.writeFileSync(STATUS_PATH, nextStatus);
if (nextReadme !== readme) fs.writeFileSync(README_PATH, nextReadme);
console.log(`status report → ${STATUS_PATH} (${rows.length} numbers)`);
for (const [section, list] of Object.entries(bySection)) {
  console.log(`  ${section}:`);
  for (const r of list) console.log(`    ${r.label}: ${r.value}  [${r.source}]`);
}
if (nextReadme !== readme) console.log(`README table updated (${README_PATH})`);
