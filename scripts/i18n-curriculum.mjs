let src = fs.readFileSync(path, "utf8");
const declRe = /^(export )?const ([a-z]{2}): Dict = \{$/gm;
let applied = 0;

for (const [code, entries] of Object.entries(T)) {
  const all = [...src.matchAll(/^(export )?const ([a-z]{2}): Dict = \{$/gm)];
  const found = all.find((m) => m[2] === code);
  if (!found) throw new Error(`dictionary ${code} not found — aborting`);
  const insertAt = (found.index ?? 0) + found[0].length;
  // Idempotent: a key already present in THIS dictionary is left untouched, so
  // re-running the script can never produce a duplicate-property build error.
  // The check must be scoped to this dictionary's own block — scanning the whole
  // file made the first patch hide every later dictionary from itself.
  const nextStart = all.find((m) => (m.index ?? 0) > (found.index ?? 0))?.index ?? src.length;
  const block = src.slice(insertAt, nextStart);
  const fresh = Object.entries(entries).filter(([k]) => !block.includes(`${JSON.stringify(k)}:`));
  if (fresh.length === 0) { applied++; continue; }
  const added = "\n" + fresh
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join("\n");
  src = src.slice(0, insertAt) + added + src.slice(insertAt);
  applied++;
}

if (applied !== 15) throw new Error(`only ${applied}/15 dictionaries patched — aborting`);
fs.writeFileSync(path, src);
