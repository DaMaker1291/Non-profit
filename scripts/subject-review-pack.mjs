#!/usr/bin/env node
// ── FIVE LESSONS A SUBJECT TEACHER CAN ACTUALLY REVIEW ──────────────────────
//
// A review pack that contains only multiple-choice items cannot answer the
// question a subject teacher asks first: "is the teaching right?" This exports
// one representative authored lesson from each of the five subjects with its
// explanation, worked example, misconceptions, assessment, model answers,
// marking criteria, transfer task and curriculum reference.
//
// It is a REVIEW AID, not approval. Nothing here is marked reviewed, and the
// output repeats the authored review state so a reader cannot mistake the pack
// for a sign-off.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { compileEngines } from "./compile-engines.mjs";

compileEngines();
const require = createRequire(import.meta.url);
const { AUTHORED_LESSONS } = require("../.verify/lessons/authored/index.js");
const { getConcept } = require("../.verify/genome.js");

const CHOSEN = [
  { subject: "maths", conceptId: "data-charts", why: "A table part, a pie-angle calculation and a representation-choice explanation." },
  { subject: "physics", conceptId: "motion-graphs", why: "A graph, a plotted series and a follow-through read-off, with the gradient/area distinction." },
  { subject: "chemistry", conceptId: "acids-bases", why: "A practical-adjacent topic whose assessment asks for explanation and ion reasoning." },
  { subject: "biology", conceptId: "photosynthesis", why: "A gap-fill and matching assessment alongside a constructed explanation of limiting factors." },
  { subject: "computing", conceptId: "what-is-code", why: "Code tracing and debugging, with an explanation of what a trace proves." },
];

const byId = new Map(AUTHORED_LESSONS.map((lesson) => [lesson.conceptId, lesson]));
const missing = CHOSEN.filter((row) => !byId.has(row.conceptId));
if (missing.length) {
  console.error(`missing authored lessons: ${missing.map((row) => row.conceptId).join(", ")}`);
  process.exit(1);
}

const record = {
  generatedBy: "scripts/subject-review-pack.mjs",
  generatedAt: new Date().toISOString(),
  contract: "openmind.subject-review-pack/1.0",
  reviewState: "unreviewed",
  note: "Representative content for qualified subject teachers. This pack records no review and no learner result.",
  lessons: CHOSEN.map((row) => {
    const lesson = byId.get(row.conceptId);
    const meta = getConcept(row.conceptId);
    return {
      subject: row.subject,
      conceptId: row.conceptId,
      title: meta?.title ?? row.conceptId,
      whyChosen: row.why,
      version: lesson.version,
      declaredStatus: lesson.declaredStatus,
      curriculum: lesson.curriculum,
      prerequisites: lesson.priorKnowledge.conceptIds,
      objectives: lesson.objectives,
      priorKnowledge: lesson.priorKnowledge.check,
      introduction: lesson.introduction,
      explanation: lesson.explanation,
      representations: lesson.representations.map((representation) => ({
        id: representation.id,
        kind: representation.kind,
        body: representation.body,
        caption: representation.caption,
        notation: representation.notation,
      })),
      workedExamples: lesson.workedExamples,
      misconceptions: lesson.misconceptions,
      guidedPractice: lesson.guidedPractice,
      assessment: lesson.assessment,
      transfer: lesson.transfer,
      retrieval: lesson.retrieval,
      summary: lesson.summary,
      accessibility: lesson.accessibility,
      translations: lesson.translations,
      reviews: lesson.reviews,
      learnerTesting: lesson.learnerTesting,
    };
  }),
};

fs.mkdirSync("audit", { recursive: true });
fs.writeFileSync("audit/subject-review-pack.json", `${JSON.stringify(record, null, 2)}\n`);

const md = [
  "# Subject review pack — five representative lessons",
  "",
  `Generated by \`scripts/subject-review-pack.mjs\` on ${record.generatedAt}.`,
  "",
  "**Review state: unreviewed.** This is content for a qualified subject teacher to read. It is not an approval, and the repository records **0 educator-reviewed and 0 learner-tested** lessons. A reviewer's decision belongs in the review record, with their name and date; this pack does not invent either.",
  "",
  "## What the reviewer is asked to judge",
  "",
  "For each lesson:",
  "",
  "1. Is the explanation correct, complete enough for the stated level, and free of a misleading simplification?",
  "2. Does each worked example model the reasoning, not only the answer?",
  "3. Is each misconception a real learner belief, and does the correction explain why it fails?",
  "4. Does every assessment item ask what the objective claims, and is the mark scheme sufficient for a different teacher to apply consistently?",
  "5. Are the units, diagrams, tables and graph readings correct and unambiguous on paper?",
  "6. Is the transfer task genuinely new, or only a reworded practice item?",
  "7. What must change before this lesson is used with learners?",
  "",
  "Record the lesson version you reviewed. A later edit invalidates the review. Use [`docs/TEACHER_REVIEW_FORM.md`](./TEACHER_REVIEW_FORM.md) for the per-lesson decision, evidence and required changes; this pack supplies the content that form asks about.",
  "",
  "## Coverage",
  "",
  "| Subject | Lesson | Version | Assessment items | Review state |",
  "| --- | --- | --- | ---: | --- |",
  ...record.lessons.map((lesson) =>
    `| ${lesson.subject} | \`${lesson.conceptId}\` — ${lesson.title} | ${lesson.version} | ${lesson.assessment.length} | ${lesson.declaredStatus} · ${lesson.reviews.length} reviews · ${lesson.learnerTesting.length} learner tests |`),
  "",
  "The five lessons are representative, not a random sample. They were chosen because each carries a different assessment demand: a table and pie calculation, a plotted graph and read-off, a chemistry explanation, a biology gap-fill/matching set, and code tracing. Reviewing them does **not** make the other 130 lessons reviewed.",
  "",
];

for (const lesson of record.lessons) {
  md.push(
    `---`,
    "",
    `## ${lesson.subject}: ${lesson.title} (\`${lesson.conceptId}\`)`,
    "",
    `**Why this lesson:** ${lesson.whyChosen}`,
    "",
    `**Curriculum:** ${lesson.curriculum.reference} · ${lesson.curriculum.level}`,
    "",
    `**Prerequisites:** ${lesson.prerequisites.length ? lesson.prerequisites.join(", ") : "none declared"}`,
    "",
    `**Version:** ${lesson.version} · **Declared status:** ${lesson.declaredStatus} · **Reviews:** ${lesson.reviews.length} · **Learner testing:** ${lesson.learnerTesting.length}`,
    "",
    "### Objectives",
    "",
    ...lesson.objectives.map((objective) => `- **${objective.statement}**  \n  Evidence: ${objective.evidence}`),
    "",
    "### Explanation",
    "",
    ...lesson.explanation.flatMap((section) => [`#### ${section.heading}`, "", ...section.paragraphs, ""]),
    "### Representations",
    "",
    ...lesson.representations.flatMap((representation) => [
      `**${representation.kind}** — ${representation.body}`,
      "",
      ...(representation.notation ? ["```text", representation.notation, "```", ""] : []),
      ...(representation.caption ? [`Caption: ${representation.caption}`, ""] : []),
    ]),
    "### Worked example",
    "",
    ...lesson.workedExamples.flatMap((example) => [
      `**${example.prompt}**`,
      "",
      ...example.steps.map((step, index) => `${index + 1}. **${step.move}** — ${step.why}`),
      "",
      `Answer: ${example.answer}`,
      "",
    ]),
    "### Misconceptions",
    "",
    ...lesson.misconceptions.flatMap((misconception) => [
      `- **Wrong belief:** ${misconception.belief}`,
      `  **Why it fails:** ${misconception.whyItFails}`,
      `  **Correction:** ${misconception.correction}`,
    ]),
    "",
    "### Assessment and mark scheme",
    "",
  );
  for (const item of lesson.assessment) {
    md.push(
      `#### ${item.id} · ${item.kind}`,
      "",
      item.prompt,
      "",
      `**Model answer:** ${item.modelAnswer}`,
      "",
      "**Marking criteria:**",
      "",
      ...item.marking.map((criterion, index) => `${index + 1}. ${criterion}`),
      "",
    );
    if (item.structured) {
      md.push("**Structured parts:**", "");
      for (const part of item.structured.parts) {
        md.push(`- (${part.id}) ${part.prompt} — ${part.marks} mark${part.marks === 1 ? "" : "s"}${part.response ? ` · response: ${part.response}` : ""}`);
      }
      md.push("");
    }
    if (item.gaps) md.push(`**Gaps:** ${item.gaps.gaps.map((gap, index) => `${index + 1}. ${gap.label} (${gap.accepted.join(" / ")})`).join("; ")}`, "");
    if (item.matching) md.push(`**Pairs:** ${item.matching.left.map((left) => left.text).join("; ")}`, "");
    if (item.diagram) md.push(`**Diagram labels:** ${item.diagram.labels.map((label) => label.text).join("; ")}`, "");
  }
  md.push(
    "### Transfer",
    "",
    ...lesson.transfer.map((task) => `**${task.prompt}**  \nWhy it transfers: ${task.whyItTransfers}  \nAnswer: ${task.answer}`),
    "",
    "### Retrieval",
    "",
    ...lesson.retrieval.map((item) => `- (${item.when}) ${item.prompt}  \n  Answer: ${item.answer}`),
    "",
    "### Accessibility alternatives",
    "",
    ...lesson.accessibility.map((alternative) => `- **${alternative.need}:** ${alternative.alternative}`),
    "",
    "### Reviewer decision",
    "",
    "```text",
    "reviewer name:",
    "role / subject:",
    "date:",
    "lesson version reviewed:",
    "decision: approve / approve with changes / reject",
    "required changes:",
    "```",
    "",
  );
}

md.push(
  "---",
  "",
  "## What this pack does not establish",
  "",
  "- It does not claim any lesson is approved.",
  "- It does not claim the five lessons represent the quality of all 135.",
  "- It does not replace a learner pilot, and it contains no learner data.",
  "- It does not verify physical print, assistive technology or a school network.",
  "",
  "The supervised learner-pilot design is in [`docs/PILOT_PROTOCOL.md`](./PILOT_PROTOCOL.md). Human review and learner testing remain separate from the software checks.",
  "",
);

fs.writeFileSync("docs/SUBJECT_REVIEW_PACK.md", md.join("\n"));
console.log(`subject review pack: ${record.lessons.length} lessons across ${new Set(record.lessons.map((row) => row.subject)).size} subjects`);
console.log("wrote audit/subject-review-pack.json and docs/SUBJECT_REVIEW_PACK.md");
